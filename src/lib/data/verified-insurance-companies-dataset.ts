import crypto from 'crypto'

export function getDeterministicUuid(sourceId: string): string {
  const hash = crypto.createHash('sha1').update(`INSURANCE_COMPANY:${sourceId}`).digest('hex')
  return [
    hash.substring(0, 8),
    hash.substring(8, 12),
    '5' + hash.substring(13, 16),
    ((parseInt(hash.substring(16, 18), 16) & 0x3f) | 0x80).toString(16) + hash.substring(18, 20),
    hash.substring(20, 32),
  ].join('-')
}

